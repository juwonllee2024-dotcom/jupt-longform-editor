test('runs source-mode selection and passes source media to the renderer', async () => {
  const jobDir = await mkdtemp(path.join(tmpdir(), 'juwon-longform-run-'));
  await mkdir(path.join(jobDir, 'work'), { recursive: true });
  const store = createMemoryStore();
  const koreanWordsPath = path.join(jobDir, 'korean-words.json');
  await writeFile(koreanWordsPath, JSON.stringify([{ word: '소스', start: 0, end: 1 }]), 'utf8');
  const clips = [0, 100, 200, 300, 400].map((start, index) => ({
    id: `clip_${index + 1}`,
    sourceStartSec: start,
    sourceEndSec: start + 78,
    durationSec: 78,
    topic: `topic-${index + 1}`,
    topicGroup: `topic-${index + 1}`,
    summary: `block ${index + 1}`,
    whyKept: 'covers a distinct idea',
    confidence: 0.9,
    sourceRef: 'source#fixture',
  }));
  let renderInput;
  const runner = createLongformCondenseRunner({
    store,
    ingest: async () => manifest,
    transcribeSource: async () => ({
      version: 1,
      language: 'en',
      durationSeconds: 1200,
      segments: [{ id: 'segment_001', start: 0, end: 4, text: 'Source.' }],
      words: [{ word: 'Source', start: 0, end: 1 }],
    }),
    chapterize: async () => [],
    select: async () => ({
      targetDurationSec: 390,
      selectedDurationSec: 390,
      clips,
      coverage: [],
      dropped: [],
      warnings: [],
    }),
    timeline: mapCondenseTimeline,
    render: async (input) => {
      renderInput = input;
      return {
        reviewPath: path.join(jobDir, 'work', 'review.mp4'),
        renderedSegmentIds: input.plan.segments.map((segment) => segment.id),
        composition: { durationInFrames: 11_700 },
      };
    },
    qa: async () => ({ passed: true, critical: [], warnings: [], metrics: {} }),
    review: async () => {
      const previewPath = path.join(jobDir, 'output', 'v001', 'preview.mp4');
      await mkdir(path.dirname(previewPath), { recursive: true });
      await writeFile(previewPath, 'fixture-preview', 'utf8');
      return { previewPath };
    },
  });

  const result = await runner.run({
    jobId: manifest.jobId,
    jobDir,
    targetDurationSec: 390,
    requiredTopics: [],
    koreanWordsPath,
  });
  assert.equal(result.state, 'ready-for-review');
  assert.deepEqual(store.transitions(), [
    'validating',
    'transcribing',
    'planning',
    'matching',
    'rendering',
    'checking',
    'ready-for-review',
  ]);
  assert.equal(renderInput.mode, 'longform-condense');
  assert.equal(renderInput.media.source_main.kind, 'video');
  assert.deepEqual(renderInput.sourceTranscript.koreanWords, [{ word: '소스', start: 0, end: 1 }]);
  const editPlan = JSON.parse(await readFile(path.join(jobDir, 'work', 'edit-plan.json'), 'utf8'));
  assert.equal(editPlan.durationFrames, 11_700);
  assert.ok(editPlan.segments.every((segment) => segment.layout === 'source-full'));
});

test('keeps long-form review revision and approval local-only', async () => {
  const revisionStore = createMemoryStore('ready-for-review');
  const revisionRunner = createLongformCondenseRunner({
    store: revisionStore,
    verifyApproval: async () => true,
  });
  await revisionRunner.revise({
    jobDir: 'C:\\fixture\\longform',
    fromStage: 'planning',
    note: 'Keep the product demonstration chapter.',
  });
  assert.equal(revisionStore.invalidatedFrom(), 'plan');
  assert.equal((await revisionRunner.status({ jobDir: 'C:\\fixture\\longform' })).state, 'revision-requested');

  const approvalStore = createMemoryStore('ready-for-review');
  const approvalRunner = createLongformCondenseRunner({
    store: approvalStore,
    verifyApproval: async () => true,
  });
  await approvalRunner.approve({
    jobDir: 'C:\\fixture\\longform',
    version: 'v001',
    outputSha256: 'a'.repeat(64),
  });
  assert.equal((await approvalRunner.status({ jobDir: 'C:\\fixture\\longform' })).state, 'approved');
});

test('default approval verifies the local preview hash and QA report', async () => {
  const jobDir = await mkdtemp(path.join(tmpdir(), 'juwon-longform-approval-'));
  const outputDir = path.join(jobDir, 'output', 'v001');
  await mkdir(outputDir, { recursive: true });
  const preview = Buffer.from('preview-bytes');
  await writeFile(path.join(outputDir, 'preview.mp4'), preview);
  await writeFile(path.join(outputDir, 'edit-report.json'), JSON.stringify({ passed: true }));
  const outputSha256 = createHash('sha256').update(preview).digest('hex');
  const runner = createLongformCondenseRunner({ store: createMemoryStore('ready-for-review') });
  await runner.approve({ jobDir, version: 'v001', outputSha256 });
  assert.equal((await runner.status({ jobDir })).state, 'approved');
});
