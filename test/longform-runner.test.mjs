function createMemoryStore(initial = 'queued') {
  let state = initial;
  const transitions = [];
  let invalidatedFrom = null;
  return {
    initialize: async () => ({ state }),
    withLock: async (action) => action(),
    status: async () => ({ state }),
    transition: async (next) => {
      state = next;
      transitions.push(next);
      return { state };
    },
    recordStage: async () => {},
    invalidateFrom: async (stage) => { invalidatedFrom = stage; },
    invalidatedFrom: () => invalidatedFrom,
    transitions: () => [...transitions],
  };
}

const manifest = {
  version: 1,
  mode: 'longform-condense',
  jobId: 'video_longform_001',
  inputHash: 'a'.repeat(64),
  source: {
    id: 'source_main',
    path: 'input/source/main.mp4',
    sha256: 'b'.repeat(64),
    durationSeconds: 1200,
    durationFrames: 36_000,
    width: 1920,
    height: 1080,
  },
  rights: { status: 'licensed', note: 'fixture' },
  warnings: [],
};

test('source-mode blocks honestly when English transcript provider fails', async () => {
  const store = createMemoryStore();
  const runner = createLongformCondenseRunner({
    store,
    ingest: async () => manifest,
    transcribeSource: async () => { throw new Error('provider unavailable'); },
  });
  await assert.rejects(
    () => runner.run({
      jobId: manifest.jobId,
      jobDir: 'C:\\fixture\\job',
      targetDurationSec: 390,
    }),
    /longform condense blocked/,
  );
  assert.equal((await runner.status()).state, 'blocked');
  assert.deepEqual(store.transitions(), ['validating', 'transcribing', 'blocked']);
});

test('downloads a YouTube URL before ingest when sourceUrl is provided', async () => {
  const store = createMemoryStore();
  let downloadedUrl;
  let downloadedRights;
  const runner = createLongformCondenseRunner({
    store,
    downloadYoutubeSource: async ({ url, personalPermission, permissionNote }) => {
      downloadedUrl = url;
      downloadedRights = { personalPermission, permissionNote };
    },
    ingest: async () => {
      assert.equal(downloadedUrl, 'https://www.youtube.com/watch?v=abc123_XY');
      return manifest;
    },
    transcribeSource: async () => { throw new Error('stop after download assertion'); },
  });
  await assert.rejects(
    () => runner.run({
      jobId: manifest.jobId,
      jobDir: 'C:\\fixture\\job',
      sourceUrl: 'https://www.youtube.com/watch?v=abc123_XY',
      personalPermission: true,
      permissionNote: 'email permission confirmed',
    }),
    /longform condense blocked/,
  );
  assert.equal(downloadedUrl, 'https://www.youtube.com/watch?v=abc123_XY');
  assert.deepEqual(downloadedRights, {
    personalPermission: true,
    permissionNote: 'email permission confirmed',
  });
});

